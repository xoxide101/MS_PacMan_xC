type Wave = OscillatorType;

interface TrackPattern {
  id: string;
  title: string;
  bpm: number;
  stepsPerBeat: number; // 2 = 8th notes, 4 = 16th notes
  leadWave: Wave;
  leadGain: number;
  leadDecay: number;
  /** Optional dedicated 4th pitched voice (counter-melody / brass horn / chord harmony). Auto-derived if omitted. */
  harmonyWave?: Wave;
  harmonyGain?: number;
  harmonyDecay?: number;
  harmony?: number[];
  arpWave: Wave;
  arpGain: number;
  arpDecay: number;
  bassWave: Wave;
  bassGain: number;
  bassDecay: number;
  /** Subtle dual-oscillator chorus detune in cents for brass/synth fullness */
  detuneCents?: number;
  /** MIDI note numbers (0 = rest) */
  lead: number[];
  /** Arpeggio / string pad channel (0 = rest) */
  arp: number[];
  /** Bassline MIDI note numbers (0 = rest) */
  bass: number[];
  /** Drum hits per step: 0=none, 1=kick, 2=snare, 3=hihat, 4=kick+hat, 5=snare+hat, 6=timpani, 7=kick+crash */
  drums: number[];
  /** Subtle master volume scale */
  volume?: number;
  /** Render this track through the multi-harmonic acoustic Concert Grand Piano & hall reverb engine */
  pianoMode?: boolean;
  /** Reverb wet balance for pianoMode (default 0.36) */
  reverbWet?: number;
}

