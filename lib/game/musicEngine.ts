class ArcadeMusicEngine {
  private ctx: AudioContext | null = null;
  private masterBus: GainNode | null = null;
  private compressor: DynamicsCompressorNode | null = null;
  private noiseBuf: AudioBuffer | null = null;
  private timer: number | null = null;
  private playing = false;
  private musicEnabled = true;
  private muted = false;
  private activeGameId: string | null = null;
  private currentTrack: TrackPattern | null = null;
  private stepIdx = 0;
  private nextStepTime = 0;

  private ensureContext(): AudioContext | null {
    if (typeof window === 'undefined') return null;
    const AudioCtx =
      window.AudioContext ||
      (window as unknown as { webkitAudioContext: typeof AudioContext }).webkitAudioContext;
    if (!AudioCtx) return null;
    if (!this.ctx) {
      this.ctx = new AudioCtx();
      // Studio-balanced master bus so 4+ pitched voices + percussion stay rich, warm, and never clip
      this.masterBus = this.ctx.createGain();
      this.masterBus.gain.value = 1.05;
      if (typeof this.ctx.createDynamicsCompressor === 'function') {
        this.compressor = this.ctx.createDynamicsCompressor();
        this.compressor.threshold.value = -16;
        this.compressor.knee.value = 18;
        this.compressor.ratio.value = 4.5;
        this.compressor.attack.value = 0.004;
        this.compressor.release.value = 0.12;
        this.masterBus.connect(this.compressor);
        this.compressor.connect(this.ctx.destination);
      } else {
        this.masterBus.connect(this.ctx.destination);
      }
    }
    if (this.ctx.state === 'suspended') {
      void this.ctx.resume();
    }
    if (!this.noiseBuf && this.ctx) {
      const length = Math.floor(this.ctx.sampleRate * 0.28);
      const buf = this.ctx.createBuffer(1, length, this.ctx.sampleRate);
      const data = buf.getChannelData(0);
      for (let i = 0; i < length; i++) {
        data[i] = Math.random() * 2 - 1;
      }
      this.noiseBuf = buf;
    }
    return this.ctx;
  }

  public getTrackTitle(gameId: string): string {
    const key = GAME_TO_TRACK[gameId] ?? 'arcade_cheerful';
    return TRACKS[key]?.title ?? 'Arcade Synth BGM';
  }

  public isMusicEnabled(): boolean {
    return this.musicEnabled;
  }

  public setMusicEnabled(enabled: boolean): void {
    this.musicEnabled = enabled;
    if (!enabled) {
      this.stopScheduler();
    } else if (this.activeGameId && !this.muted) {
      this.startTrackForGame(this.activeGameId);
    }
  }

  public setMuted(muted: boolean): void {
    this.muted = muted;
    if (muted) {
      this.stopScheduler();
    } else if (this.activeGameId && this.musicEnabled) {
      this.startTrackForGame(this.activeGameId);
    }
  }

  public startTrackForGame(gameId: string): void {
    const trackKey = GAME_TO_TRACK[gameId] ?? 'arcade_cheerful';
    const track = TRACKS[trackKey] ?? TRACKS.arcade_cheerful;

    const sameTrackRunning =
      this.playing && this.currentTrack?.id === track.id && this.activeGameId === gameId;
    this.activeGameId = gameId;
    this.currentTrack = track;

    if (!this.musicEnabled || this.muted) {
      this.stopScheduler();
      return;
    }
    if (sameTrackRunning) return;

    const ctx = this.ensureContext();
    if (!ctx) return;

    this.stopScheduler();
    this.playing = true;
    this.stepIdx = 0;
    this.nextStepTime = ctx.currentTime + 0.05;

    this.timer = window.setInterval(() => {
      this.schedulerTick();
    }, 35);
  }

  public stop(): void {
    this.activeGameId = null;
    this.stopScheduler();
  }

  public pause(): void {
    this.stopScheduler();
  }

  private stopScheduler(): void {
    this.playing = false;
    if (this.timer !== null) {
      window.clearInterval(this.timer);
      this.timer = null;
    }
  }

  private schedulerTick(): void {
    if (!this.playing || !this.ctx || !this.currentTrack || this.muted || !this.musicEnabled) {
      return;
    }
    const ctx = this.ctx;
    if (ctx.state === 'suspended') return;

    const track = this.currentTrack;
    const stepDur = 60 / track.bpm / track.stepsPerBeat;
    const lookahead = 0.14;

    // Catch up if browser tab slept
    if (this.nextStepTime < ctx.currentTime - 0.3) {
      this.nextStepTime = ctx.currentTime + 0.04;
    }

    while (this.nextStepTime < ctx.currentTime + lookahead) {
      this.scheduleStep(ctx, track, this.stepIdx, this.nextStepTime);
      this.nextStepTime += stepDur;
      this.stepIdx = (this.stepIdx + 1) % track.lead.length;
    }
  }

  private getOutputNode(ctx: AudioContext): AudioNode {
    return this.masterBus ?? ctx.destination;
  }

  private scheduleTone(
    ctx: AudioContext,
    freq: number,
    time: number,
    dur: number,
    wave: Wave,
    gainVal: number,
    filterHz?: number,
    detuneCents = 0
  ): void {
    const osc = ctx.createOscillator();
    const gain = ctx.createGain();
    osc.type = wave;
    osc.frequency.setValueAtTime(freq, time);
    if (detuneCents !== 0) {
      osc.detune.setValueAtTime(detuneCents, time);
    }

    gain.gain.setValueAtTime(0.0001, time);
    gain.gain.linearRampToValueAtTime(gainVal, time + 0.009);
    gain.gain.exponentialRampToValueAtTime(0.0001, time + dur);

    if (filterHz) {
      const flt = ctx.createBiquadFilter();
      flt.type = 'lowpass';
      flt.frequency.setValueAtTime(filterHz, time);
      osc.connect(flt);
      flt.connect(gain);
    } else {
      osc.connect(gain);
    }

    gain.connect(this.getOutputNode(ctx));
    osc.start(time);
    osc.stop(time + dur + 0.02);
  }

  private scheduleDrum(ctx: AudioContext, kind: number, time: number, volScale: number): void {
    const out = this.getOutputNode(ctx);
    if (kind === 1 || kind === 4 || kind === 7) {
      // Punchy arcade kick
      const osc = ctx.createOscillator();
      const g = ctx.createGain();
      osc.type = 'triangle';
      osc.frequency.setValueAtTime(155, time);
      osc.frequency.exponentialRampToValueAtTime(38, time + 0.095);
      g.gain.setValueAtTime(0.11 * volScale, time);
      g.gain.exponentialRampToValueAtTime(0.0001, time + 0.11);
      osc.connect(g);
      g.connect(out);
      osc.start(time);
      osc.stop(time + 0.12);
    }
    if (kind === 6) {
      // Orchestral timpani / low tom boom
      const osc = ctx.createOscillator();
      const g = ctx.createGain();
      osc.type = 'triangle';
      osc.frequency.setValueAtTime(118, time);
      osc.frequency.exponentialRampToValueAtTime(62, time + 0.22);
      g.gain.setValueAtTime(0.135 * volScale, time);
      g.gain.exponentialRampToValueAtTime(0.0001, time + 0.24);
      osc.connect(g);
      g.connect(out);
      osc.start(time);
      osc.stop(time + 0.25);
    }
    if (kind === 2 || kind === 5) {
      // Crisp arcade / marching snare (noise snap + body tone)
      if (this.noiseBuf) {
        const src = ctx.createBufferSource();
        src.buffer = this.noiseBuf;
        const flt = ctx.createBiquadFilter();
        flt.type = 'bandpass';
        flt.frequency.setValueAtTime(1850, time);
        const g = ctx.createGain();
        g.gain.setValueAtTime(0.056 * volScale, time);
        g.gain.exponentialRampToValueAtTime(0.0001, time + 0.095);
        src.connect(flt);
        flt.connect(g);
        g.connect(out);
        src.start(time);
        src.stop(time + 0.105);
      }
      const body = ctx.createOscillator();
      const bg = ctx.createGain();
      body.type = 'triangle';
      body.frequency.setValueAtTime(215, time);
      body.frequency.exponentialRampToValueAtTime(110, time + 0.05);
      bg.gain.setValueAtTime(0.036 * volScale, time);
      bg.gain.exponentialRampToValueAtTime(0.0001, time + 0.055);
      body.connect(bg);
      bg.connect(out);
      body.start(time);
      body.stop(time + 0.06);
    }
    if (kind === 3 || kind === 4 || kind === 5) {
      // Tight closed hi-hat tick
      if (this.noiseBuf) {
        const src = ctx.createBufferSource();
        src.buffer = this.noiseBuf;
        const flt = ctx.createBiquadFilter();
        flt.type = 'highpass';
        flt.frequency.setValueAtTime(6400, time);
        const g = ctx.createGain();
        g.gain.setValueAtTime(0.022 * volScale, time);
        g.gain.exponentialRampToValueAtTime(0.0001, time + 0.034);
        src.connect(flt);
        flt.connect(g);
        g.connect(out);
        src.start(time);
        src.stop(time + 0.042);
      }
    }
    if (kind === 7 && this.noiseBuf) {
      // Orchestral cymbal crash accent
      const src = ctx.createBufferSource();
      src.buffer = this.noiseBuf;
      const flt = ctx.createBiquadFilter();
      flt.type = 'highpass';
      flt.frequency.setValueAtTime(4200, time);
      const g = ctx.createGain();
      g.gain.setValueAtTime(0.046 * volScale, time);
      g.gain.exponentialRampToValueAtTime(0.0001, time + 0.25);
      src.connect(flt);
      flt.connect(g);
      g.connect(out);
      src.start(time);
      src.stop(time + 0.27);
    }
  }

  private scheduleStep(ctx: AudioContext, track: TrackPattern, idx: number, time: number): void {
    const vol = track.volume ?? 0.88;
    const leadNote = track.lead[idx % track.lead.length];
    const arpNote = track.arp[idx % track.arp.length];
    const bassNote = track.bass[idx % track.bass.length];
    const drum = track.drums[idx % track.drums.length];
    const detune = track.detuneCents ?? 6;

    // Channel 1: Rich Lead Melody (main voice + subtle detuned chorus twin for full arcade cabinet warmth)
    if (leadNote > 0) {
      const leadFreq = midiToFreq(leadNote);
      const leadFlt = track.leadWave === 'sawtooth' ? 3100 : 4100;
      this.scheduleTone(
        ctx,
        leadFreq,
        time,
        track.leadDecay,
        track.leadWave,
        track.leadGain * vol,
        leadFlt,
        -detune * 0.5
      );
      this.scheduleTone(
        ctx,
        leadFreq,
        time,
        track.leadDecay * 0.94,
        track.leadWave === 'square' ? 'triangle' : track.leadWave,
        track.leadGain * 0.42 * vol,
        leadFlt * 0.82,
        detune
      );
    }

    // Channel 2: Dedicated 4th Pitched Harmony / Counter-Melody Voice (explicit or lush auto-derived chordal counter-voice)
    let harmonyNote = 0;
    if (track.harmony && track.harmony.length > 0) {
      harmonyNote = track.harmony[idx % track.harmony.length];
    } else if (leadNote > 0) {
      // Auto-derive tasteful musical harmony: anchor to arp chord tone or warm 5th/octave-lower pad on strong hits
      if (arpNote > 0 && Math.abs(leadNote - arpNote) >= 3) {
        harmonyNote = arpNote + (leadNote - arpNote > 14 ? 12 : 0);
      } else if (idx % 2 === 0) {
        harmonyNote = leadNote - 5; // classic arcade fifth/fourth counter-harmony
      }
    } else if (arpNote > 0 && idx % 4 === 0) {
      // Subtle sustained chord pad on bar beats when lead rests
      harmonyNote = arpNote + 7;
    }

    if (harmonyNote > 0) {
      const hWave = track.harmonyWave ?? (track.leadWave === 'square' ? 'triangle' : 'square');
      const hGain = track.harmonyGain ?? track.leadGain * 0.56;
      const hDecay = track.harmonyDecay ?? Math.min(0.32, track.leadDecay * 1.18);
      this.scheduleTone(
        ctx,
        midiToFreq(harmonyNote),
        time,
        hDecay,
        hWave,
        hGain * vol,
        hWave === 'sawtooth' ? 2300 : 2800,
        detune * 0.65
      );
    }

    // Channel 3: Arpeggio / String Ostinato Voice
    if (arpNote > 0) {
      this.scheduleTone(
        ctx,
        midiToFreq(arpNote),
        time,
        track.arpDecay,
        track.arpWave,
        track.arpGain * vol,
        2500
      );
    }

    // Channel 4: Deep Bass + Warm Sub-Octave Layer
    if (bassNote > 0) {
      const bassFreq = midiToFreq(bassNote);
      this.scheduleTone(
        ctx,
        bassFreq,
        time,
        track.bassDecay,
        track.bassWave,
        track.bassGain * vol,
        track.bassWave === 'sawtooth' ? 1180 : 1450
      );
      // Warm sub-bass sine anchor so bass hits with full cabinet body
      if (bassFreq >= 65) {
        this.scheduleTone(
          ctx,
          bassFreq * 0.5,
          time,
          track.bassDecay * 1.1,
          'sine',
          track.bassGain * 0.44 * vol,
          420
        );
      }
    }

    // Channel 5: Multi-Piece Percussion Bus (Kick, Snare, Hi-Hat, Timpani, Crash)
    if (drum > 0) {
      this.scheduleDrum(ctx, drum, time, vol);
    }
  }
}

export const arcadeMusic = new ArcadeMusicEngine();
